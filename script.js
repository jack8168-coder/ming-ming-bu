// 判斷兩五行關係
function getWuxingRelation(a, b) {
  if (a === b) return '比和';
  if (WUXING_SHENG[a] === b) return a + '生' + b;
  if (WUXING_SHENG[b] === a) return b + '生' + a;
  if (WUXING_KE[a] === b) return a + '剋' + b;
  if (WUXING_KE[b] === a) return b + '剋' + a;
  return '';
}

