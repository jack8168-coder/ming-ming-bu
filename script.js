// 補充星曜計算
function addExtraStars(zw, hourStr, gender) {
  // ziwei core 使用隱式全域變數 (y1Pos, y2Pos, m, d, lPos, bPos, f)
  const y1Pos = window.y1Pos;
  const y2Pos = window.y2Pos;
  const hPos = EarthlyBranches.indexOf(hourStr);
  const m = window.m;
  const d = window.d;
  const lPos = window.lPos;
  const bPos = window.bPos;
  const fBureau = window.f;
  if (y1Pos === undefined || y2Pos === undefined || m === undefined) return;
  const isYangMan = (y1Pos % 2 === 0);
  // 陽男陰女順行, 陰男陽女逆行
  const forward = (gender === 'M') ? isYangMan : !isYangMan;

  function addStar(idx, name) {
    if (typeof idx !== 'number' || isNaN(idx) || idx < 0 || idx > 11) return;
    if (!zw[idx]) return;
    if (!zw[idx].StarD) zw[idx].StarD = [];
    if (!zw[idx].StarD.includes(name)) zw[idx].StarD.push(name);
  }

  // === 月支系 ===
  // 天刑：以酉宮(9)起正月順數至生月
  addStar((9 + m - 1) % 12, '天刑');
  // 天姚：以丑宮(1)起正月順數至生月
  addStar((1 + m - 1) % 12, '天姚');
  // 解神（月解）：兩個月共一宮 — 1,2月申 / 3,4月戌 / 5,6月子 / 7,8月寅 / 9,10月辰 / 11,12月午
  addStar((8 + Math.floor((m - 1) / 2) * 2) % 12, '解神');
  // 天巫 (月支)
  // 天巫：1,5,9月巳 / 2,6,10月申 / 3,7,11月寅 / 4,8,12月亥
  const tianWu = [5, 8, 2, 11, 5, 8, 2, 11, 5, 8, 2, 11]; // 月 1-12
  addStar(tianWu[m - 1], '天巫');

  // === 年支系 ===
  // 天哭：以午(6)起子(0)逆行年支
  addStar((6 - y2Pos + 12) % 12, '天哭');
  // 天虛：以午(6)起子(0)順行年支
  addStar((6 + y2Pos) % 12, '天虛');
  // 孤辰 / 寡宿
  const guChen = { 2:5, 3:5, 4:5, 5:8, 6:8, 7:8, 8:11, 9:11, 10:11, 11:2, 0:2, 1:2 };
  const guaSu  = { 2:1, 3:1, 4:1, 5:4, 6:4, 7:4, 8:7, 9:7, 10:7, 11:10, 0:10, 1:10 };
  addStar(guChen[y2Pos], '孤辰');
  addStar(guaSu[y2Pos], '寡宿');
  // 華蓋 (三合局末支)
  const huaGai = { 2:10, 6:10, 10:10, 8:4, 0:4, 4:4, 5:1, 9:1, 1:1, 11:7, 3:7, 7:7 };
  addStar(huaGai[y2Pos], '華蓋');
  // 陰煞 (月支)
  // 陰煞：正月起寅、每月退兩宮（寅子戌申午辰循環）
  const yinShaMap = [2, 0, 10, 8, 6, 4, 2, 0, 10, 8, 6, 4];
  addStar(yinShaMap[m - 1], '陰煞');
  // 破碎
  // 破碎：子午卯酉年→巳 / 丑辰未戌年→丑 / 寅巳申亥年→酉（年支 mod 3 分組）
  addStar([5, 1, 9][y2Pos % 3], '破碎');
  // 蜚廉
  // 蜚廉：子丑寅年→申酉戌 / 卯辰巳年→巳午未 / 午未申年→寅卯辰 / 酉戌亥年→亥子丑
  const feiLian = { 0:8, 1:9, 2:10, 3:5, 4:6, 5:7, 6:2, 7:3, 8:4, 9:11, 10:0, 11:1 };
  addStar(feiLian[y2Pos], '蜚廉');
  // 天德 / 月德 略...
  // 天才：命宮起子順至生年支
  addStar((lPos + y2Pos) % 12, '天才');
  // 天壽：身宮起子順至生年支
  addStar((bPos + y2Pos) % 12, '天壽');

  // === 三台、八座 (依月起左輔右弼 + 日) ===
  // 三台：左輔(辰/4起初一順數)位置 + 日 - 1
  const zuoFuPos = (4 + m - 1) % 12;
  const youBiPos = (10 - m + 1 + 120) % 12;
  addStar((zuoFuPos + d - 1) % 12, '三台');
  addStar((youBiPos - d + 1 + 120) % 12, '八座');

  // === 恩光、天貴 (依日起文昌文曲退一位) ===
  const wenChangPos = (10 - hPos + 12) % 12;  // 文昌
  const wenQuPos = (4 + hPos) % 12;            // 文曲
  addStar((wenChangPos + d - 2 + 120) % 12, '恩光');
  addStar((wenQuPos + d - 2 + 120) % 12, '天貴');

  // === 台輔、封誥 (依時) ===
  // 台輔：午宮起子時順數
  addStar((6 + hPos) % 12, '台輔');
  addStar((2 + hPos) % 12, '封誥');

  // === 天福、天官 (年干) ===
  // 天福貴人：甲酉 乙申 丙子 丁亥 戊卯 己寅 庚午 辛巳 壬午 癸巳
  const tianFu = [9, 8, 0, 11, 3, 2, 6, 5, 6, 5]; // 甲乙丙丁戊己庚辛壬癸
  // 天官貴人：甲未 乙辰 丙巳 丁寅 戊卯 己酉 庚亥 辛酉 壬戌 癸午
  const tianGuan = [7, 4, 5, 2, 3, 9, 11, 9, 10, 6];
  addStar(tianFu[y1Pos] || 0, '天福');
  addStar(tianGuan[y1Pos] || 0, '天官');

  // === 長生 12 神 (依五行局起長生) ===
  const changShengStart = { '水二局': 8, '火六局': 2, '土五局': 8, '木三局': 11, '金四局': 5 };
  const csStart = changShengStart[fBureau];
  if (csStart !== undefined) {
    const order = ['長生','沐浴','冠帶','臨官','帝旺','衰','病','死','墓','絕','胎','養'];
    for (let i = 0; i < 12; i++) {
      const idx = forward ? (csStart + i) % 12 : (csStart - i + 120) % 12;
      addStar(idx, order[i]);
    }
  }

  // === 博士 12 星 (依祿存起博士) ===
  // 祿存位置
  const luCun = { 0:2, 1:3, 2:5, 3:6, 4:5, 5:6, 6:8, 7:9, 8:11, 9:0 };
  const luPos = luCun[y1Pos];
  if (luPos !== undefined) {
    const boshiOrder = ['博士','力士','青龍','小耗','將軍','奏書','飛廉','喜神','病符','大耗','伏兵','官府'];
    for (let i = 0; i < 12; i++) {
      const idx = forward ? (luPos + i) % 12 : (luPos - i + 120) % 12;
      addStar(idx, boshiOrder[i]);
    }
  }
}

function computeAndRenderZiwei() {
  const dateStr = document.getElementById('birthDate').value;
  const { shichen: hourStr } = parseBirthTime();
  const genderStr = document.getElementById('gender').value;

  if (!dateStr || !hourStr || !genderStr) {
    // 不夠資料，隱藏命盤但更新農曆
    document.getElementById('ziweiSection').classList.add('hidden');
    if (dateStr) {
      try {
        const d = new Date(dateStr);
        Lunar(0, d.getFullYear(), d.getMonth() + 1, d.getDate());
        document.getElementById('lunarDateDisplay').textContent =
          `${GanGB[gan.y]}${ZhiGB[zhi.y]}年 ${lunar.l ? '閏' : ''}${lunar.m}月${lunar.d}日`;
      } catch (e) {
        document.getElementById('lunarDateDisplay').textContent = '-';
      }
    }
    document.getElementById('fiveElementBureau').textContent = '-';
    document.getElementById('yinYangDisplay').textContent = '-';
    // 修正：早退時同步清除紫微主星與好運指數，避免殘留舊值被報告引用
    document.getElementById('ziweiMainStar').textContent = '-';
    const lps0 = document.getElementById('luckScorePanel'); if (lps0) lps0.textContent = '-';
    const lls0 = document.getElementById('luckScoreLabel'); if (lls0) lls0.textContent = '';
    return;
  }

  const d = new Date(dateStr);
  const year = d.getFullYear();
  const month = d.getMonth() + 1;
  const day = d.getDate();
  const genderCode = genderStr === 'male' ? 'M' : 'F';

  try {
    // 設定精確小時（晚子時 23:00 換日判斷，與八字一致）
    const { hour: zwHour } = parseBirthTime();
    solar.h = (typeof zwHour === 'number' && !isNaN(zwHour)) ? zwHour : 0;
    // 計算紫微命盤
    const zw = ziwei.computeZiWei(year, month, day, hourStr, genderCode);

    // 補充其他星曜（天刑、天姚、天哭、天虛、孤辰、寡宿、華蓋、長生12神、博士12星等）
    addExtraStars(zw, hourStr, genderCode);

    // 更新右側面板資訊
    document.getElementById('lunarDateDisplay').textContent = ziwei.getLunarDay();
    document.getElementById('fiveElementBureau').textContent = ziwei.getFiveElement();
    document.getElementById('yinYangDisplay').textContent =
      `${HeavenlyStems[(lunar.y - 4) % 10]}${EarthlyBranches[(lunar.y - 4) % 12]}年 ・ ${ziwei.getYinYangGender()}`;

    // 自動填入紫微主星欄位 — 從命宮找主星 + 亮度檢查
    const mingGongIdx = zw.findIndex((p, i) => p.MangB === '【命宮】');
    if (mingGongIdx >= 0 && zw[mingGongIdx].StarA.length > 0) {
      const starNames = zw[mingGongIdx].StarA.map(s => s.replace(/<[^>]*>/g, '').substring(0, 2));
      document.getElementById('ziweiMainStar').textContent = starNames.join('、');

      // 檢查命宮主星是否多數「陷」
      const xianCount = starNames.filter(name => {
        const b = STAR_BRIGHTNESS[name];
        return b && b[mingGongIdx] === '陷';
      }).length;
      if (xianCount > 0 && xianCount >= starNames.length / 2) {
        const notesEl = document.getElementById('notes');
        if (!notesEl.value.includes('先天命宮')) {
          notesEl.value = (notesEl.value ? notesEl.value + '\n' : '') +
            '【系統提示】先天命宮星曜能量較弱（主星落陷），建議命名時加強五行補給。';
        }
      }
    }

    // 渲染命盤
    renderZiweiChart(zw, year, month, day, hourStr, genderCode);

    // 生成紫微命名建議
    generateZiweiNamingAdvice(zw, mingGongIdx);

    // 重新渲染檢核表（因為 _energyScore 已更新）
    renderPriorityChecklist();

    // 顯示命盤區域
    document.getElementById('ziweiSection').classList.remove('hidden');
  } catch (e) {
    console.error('紫微計算錯誤:', e);
    document.getElementById('ziweiSection').classList.add('hidden');
    document.getElementById('fiveElementBureau').textContent = '計算錯誤';
  }
}

