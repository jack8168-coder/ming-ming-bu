// --- 姓名加入後的五行增減列 ---
function renderNameElementRow(baziCounts) {
  const n1 = document.getElementById('name1').value;
  const n2 = document.getElementById('name2').value;
  const s = document.getElementById('surname').value;
  const row = document.getElementById('nameElementRow');
  if (!row) return;

  if (!n1 || !n2) {
    row.innerHTML = '<div class="text-xs text-green-600 mb-1">＋姓名後五行</div><div class="text-gray-400 text-center text-xs py-6">請填入完整姓名後顯示</div>';
    return;
  }

  // 確保 DOM 結構存在（可能被佔位文字取代過）
  if (!document.getElementById('nameElementGrid')) {
    row.innerHTML = '<div class="text-xs text-green-600 mb-1">＋姓名後五行</div><div class="grid grid-cols-5 gap-1 text-center text-xs" id="nameElementGrid"></div><div id="nameElementDiff" class="mt-1 text-xs text-center"></div>';
  }

  const grid = document.getElementById('nameElementGrid');
  const diff = document.getElementById('nameElementDiff');
  if (!grid || !diff) return;

  // 取得每字的部首五行和數理五行
  const sInfo = getCharInfo(s);
  const n1Info = getCharInfo(n1);
  const n2Info = getCharInfo(n2);
  if (!sInfo || !n1Info || !n2Info) { row.classList.add('hidden'); return; }

  const sRad = getCharRadicalWuxing(s);
  const n1Rad = getCharRadicalWuxing(n1);
  const n2Rad = getCharRadicalWuxing(n2);

  // 計算名字帶來的五行加成（部首1.5 + 數理0.5）
  const namePlus = { '金':0, '木':0, '水':0, '火':0, '土':0 };
  for (const el of [sRad, n1Rad, n2Rad]) { if (el && namePlus[el] !== undefined) namePlus[el] += 1.5; }
  for (const info of [sInfo, n1Info, n2Info]) { if (info?.element && namePlus[info.element] !== undefined) namePlus[info.element] += 0.5; }

  // 合計
  const total = {};
  const elements = ['木', '火', '土', '金', '水'];
  const colors = { '木':'green', '火':'red', '土':'yellow', '金':'amber', '水':'blue' };
  let gridHtml = '';
  let changes = [];

  for (const el of elements) {
    const before = Math.round((baziCounts[el] || 0) * 10) / 10;
    const plus = Math.round(namePlus[el] * 10) / 10;
    total[el] = Math.round((before + plus) * 10) / 10;
    const colorName = colors[el];
    const wasZero = before < 0.1;
    const nowFilled = total[el] >= 0.1;

    gridHtml += `<div class="p-1.5 rounded-lg bg-${colorName}-50 border border-${colorName}-200">
      <div class="font-bold text-${colorName}-700">${el}</div>
      <div class="text-sm font-black">${total[el]}</div>
      ${plus > 0 ? '<div class="text-green-600 text-xs">+' + plus + '</div>' : ''}
      ${wasZero && nowFilled ? '<div class="text-green-600 text-xs font-bold">已補!</div>' : ''}
    </div>`;
    if (plus > 0) changes.push(el + '+' + plus);
  }

  grid.innerHTML = gridHtml;

  // 智能差異分析
  const rec = getRecommendedElements();
  const stillWeak = rec.priority.filter(m => total[m] < 1.0);
  const overBoosted = rec.forbidden.filter(m => namePlus[m] > 0); // 已過旺還在補
  let diffHtml = '';

  if (stillWeak.length > 0) {
    diffHtml += `<span class="text-red-600">仍需補強：${stillWeak.join('、')}</span> `;
  }
  if (overBoosted.length > 0) {
    diffHtml += `<span class="text-amber-600">⚠ ${overBoosted.join('、')}已過旺，名字又加${overBoosted.map(e=>e).join('、')}，建議調整</span> `;
  }
  if (stillWeak.length === 0 && rec.priority.length > 0) {
    diffHtml += `<span class="text-green-600 font-bold">姓名已補足弱勢五行！</span> `;
  }
  if (changes.length > 0) {
    diffHtml += `<span class="text-gray-500 text-xs">${changes.join(' ')}</span>`;
  }
  diff.innerHTML = diffHtml || '<span class="text-gray-400">-</span>';

  row.classList.remove('hidden');
}

