// 計算所有有效 (N1劃, N2劃) 配對
function computeAllValidPairs(surnameStrokes) {
  if (validPairsSurnameStrokes === surnameStrokes && validPairsCache) {
    return validPairsCache;
  }
  const S = surnameStrokes;
  const pairs = [];

  // 天格固定 = S + 1，必須先檢查
  if (!isLucky(S + 1)) {
    validPairsCache = [];
    validPairsSurnameStrokes = S;
    return [];
  }

  for (let n1 = 3; n1 <= 24; n1++) {
    // 人格 = S + N1
    if (!isLucky(S + n1)) continue;
    for (let n2 = 3; n2 <= 24; n2++) {
      // 外格 = N2 + 1
      if (!isLucky(n2 + 1)) continue;
      // 地格 = N1 + N2
      if (!isLucky(n1 + n2)) continue;
      // 總格 = S + N1 + N2
      if (!isLucky(S + n1 + n2)) continue;
      // 計算三才
      const tianEl = getElement(S + 1);
      const renEl = getElement(S + n1);
      const diEl = getElement(n1 + n2);
      const sc = analyzeSanCai(tianEl, renEl, diEl);

      pairs.push({
        n1, n2,
        tian: S + 1,
        ren: S + n1,
        di: n1 + n2,
        wai: n2 + 1,
        zong: S + n1 + n2,
        sanCai: sc ? sc.overall : '需注意',
      });
    }
  }

  validPairsCache = pairs;
  validPairsSurnameStrokes = S;
  return pairs;
}

// 三才篩選
function getSanCaiFilter() {
  return {
    '大吉': document.getElementById('scFilterDaji')?.checked ?? true,
    '中吉': document.getElementById('scFilterZhongji')?.checked ?? true,
    '需注意': document.getElementById('scFilterWarn')?.checked ?? false,
  };
}

function getFilteredPairs(surnameStrokes) {
  const all = computeAllValidPairs(surnameStrokes);
  const filter = getSanCaiFilter();
  const filtered = all.filter(p => filter[p.sanCai] && pairPassesPriorityFilter(p.n1, p.n2));
  return filtered;
}

function onSanCaiFilterChange() {
  const filter = getSanCaiFilter();
  const activeCount = Object.values(filter).filter(Boolean).length;
  const statusEl = document.getElementById('scFilterStatus');
  if (statusEl) statusEl.textContent = activeCount < 3 ? '(篩選中)' : '';
  // 重新渲染推薦
  refreshRecommendations();
  if (recMode === 'interactive') initInteractiveMode();
}

