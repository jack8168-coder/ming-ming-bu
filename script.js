function isLucky(strokes) {
  if (strokes === null || strokes <= 0) return null;
  // 82劃等同1劃
  const normalized = strokes > 81 ? ((strokes - 1) % 81) + 1 : strokes;
  return LUCKY_STROKES.has(normalized);
}

