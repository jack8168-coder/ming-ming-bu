// P0-P3 過濾：檢查某個 (n1劃, n2劃) 組合是否通過勾選的檢核項
function pairPassesPriorityFilter(n1, n2) {
  const p0On = document.getElementById('pFilter_P0')?.checked;
  const p1On = document.getElementById('pFilter_P1')?.checked;
  const p3On = document.getElementById('pFilter_P3')?.checked;
  // P2 不適用於劃數篩選（紫微星曜與劃數無關）

  if (!p0On && !p1On && !p3On) return true; // 沒勾選任何項 = 不過濾

  const sInfo = getCharInfo(document.getElementById('surname').value);
  if (!sInfo) return true;
  const S = sInfo.kangxi;
  const baziCounts = window._baziCounts;

  // P0：檢查該劃數的數理五行是否能補足八字缺失
  if (p0On && baziCounts) {
    const weak = ['木','火','土','金','水'].filter(el => (baziCounts[el]||0) < 0.5);
    if (weak.length > 0) {
      const n1El = getElement(n1);
      const n2El = getElement(n2);
      const covered = weak.some(w => n1El === w || n2El === w);
      if (!covered) return false;
    }
  }

  // P1：三才必須相生（大吉或中吉）
  if (p1On) {
    const tianEl = getElement(S + 1);
    const renEl = getElement(S + n1);
    const diEl = getElement(n1 + n2);
    const sc = analyzeSanCai(tianEl, renEl, diEl);
    if (!sc || (sc.overall !== '大吉' && sc.overall !== '中吉')) return false;
  }

  // P3：不能造成任何五行超過 2.5
  if (p3On && baziCounts) {
    const n1El = getElement(n1);
    const n2El = getElement(n2);
    const boost = {};
    for (const el of ['木','火','土','金','水']) boost[el] = (baziCounts[el]||0);
    // 數理五行加 0.5
    if (boost[n1El] !== undefined) boost[n1El] += 0.5;
    if (boost[n2El] !== undefined) boost[n2El] += 0.5;
    // 姓氏
    if (boost[sInfo.element] !== undefined) boost[sInfo.element] += 0.5;
    for (const el of ['木','火','土','金','水']) {
      if (boost[el] > 2.5) return false;
    }
  }

  return true;
}

