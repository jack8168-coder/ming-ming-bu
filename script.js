function stepSelect(id, dir) {
  const sel = document.getElementById(id);
  if (!sel) return;
  let idx = sel.selectedIndex + dir;
  // 跳過第一個空選項
  if (idx < 1) idx = sel.options.length - 1;
  if (idx >= sel.options.length) idx = 1;
  sel.selectedIndex = idx;
  sel.dispatchEvent(new Event('change'));
}

function stepMinute(dir) {
  const input = document.getElementById('birthMinute');
  if (!input) return;
  let val = parseInt(input.value) || 0;
  val += dir;
  if (val < 0) val = 59;
  if (val > 59) val = 0;
  input.value = val;
  input.dispatchEvent(new Event('input'));
}

function initDateSelectors() {
  const yearSel = document.getElementById('birthYear');
  const monthSel = document.getElementById('birthMonth');
  const daySel = document.getElementById('birthDay');

  // 年份 1900-2049
  // 年份下限 1901：農曆對照表起點為 1900/1/31，1900年1月出生會算出 NaN
  for (let y = 2040; y >= 1901; y--) {
    const op = document.createElement('option');
    op.value = y; op.textContent = y;
    yearSel.appendChild(op);
  }
  // 月份 1-12
  for (let m = 1; m <= 12; m++) {
    const op = document.createElement('option');
    op.value = m; op.textContent = m;
    monthSel.appendChild(op);
  }
  // 日 1-31
  for (let d = 1; d <= 31; d++) {
    const op = document.createElement('option');
    op.value = d; op.textContent = d;
    daySel.appendChild(op);
  }

  // 監聽變更
  [yearSel, monthSel, daySel].forEach(sel => {
    sel.addEventListener('change', onBirthDateChange);
  });
}

