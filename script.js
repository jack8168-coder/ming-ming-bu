// --- 智能推薦引擎 ---
// 權重：八字五行缺失 90%，占星/紫微 10%
// 排除：先天已 > 1.5 的五行禁止推薦（抑制占星雜訊）
// 優先：< 0.5 的五行為最高優先補救
function getRecommendedElements() {
  const counts = window._baziCounts;
  if (!counts) return { priority: [], ok: [], forbidden: [] };

  const priority = []; // < 0.5，急需補救（90%權重）
  const ok = [];       // 0.5 ~ 1.5，可補可不補
  const forbidden = []; // > 1.5，已足夠或過旺，禁止占星建議補（抑制雜訊）

  for (const el of ['木','火','土','金','水']) {
    const v = counts[el] || 0;
    if (v < 0.5) priority.push(el);       // 急需（含完全缺失和極弱）
    else if (v <= 1.5) ok.push(el);       // 正常範圍
    else forbidden.push(el);              // 已夠旺，占星不得推薦補此五行
  }

  return { priority, ok, forbidden };
}

function getSupplementBadge(strokes) {
  const rec = getRecommendedElements();
  if (rec.priority.length === 0) return '';

  const el = getElement(strokes);

  // 禁止推薦已過旺的五行
  if (rec.forbidden.includes(el)) {
    return `<span class="inline-block px-1.5 py-0.5 rounded-full text-xs font-bold bg-gray-100 text-gray-400 border border-gray-200 ml-1">已旺</span>`;
  }

  // 最高優先推薦
  if (rec.priority.includes(el)) {
    return `<span class="inline-block px-1.5 py-0.5 rounded-full text-xs font-bold bg-red-100 text-red-700 border border-red-300 ml-1">急需補${el}</span>`;
  }

  return '';
}

