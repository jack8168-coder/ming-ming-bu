function isCommonChar(ch) {
  // 排除純部首和罕用部件
  if (EXCLUDED_CHARS.has(ch)) return false;
  // 排除簡體字
  if (SIMPLIFIED_CHARS.has(ch)) return false;
  const code = ch.codePointAt(0);
  // CJK Unified Ideographs 基本區
  if (code >= 0x4E00 && code <= 0x9FFF) return true;
  // 特別保留頤
  if (ch === '頤') return true;
  return false;
}

function getCharsByStrokes(strokes) {
  const common = COMMON_NAME_CHARS[strokes] || '';
  // 只保留實際 kangxi 筆劃等於此劃數的常用字（避免放錯位置）
  const commonSet = new Set();
  for (const ch of common) {
    if (kangxiDB[ch] === strokes) commonSet.add(ch);
  }
  const others = [];
  const filterCommon = document.getElementById('filterCommonOnly')?.checked ?? true;

  for (const [ch, st] of Object.entries(kangxiDB)) {
    if (st === strokes && !commonSet.has(ch)) {
      if (filterCommon && !isCommonChar(ch)) continue;
      others.push(ch);
    }
  }
  return { common: [...commonSet], others: others.sort() };
}

