const ELEMENT_COLOR_MAP = { '木':'text-green-700', '火':'text-red-600', '土':'text-yellow-700', '金':'text-amber-600', '水':'text-blue-600' };

function renderCharGrid(chars, maxShow, onClickFn, strokes) {
  const { common, others } = chars;
  const all = [...common, ...others];
  const elColor = strokes ? (ELEMENT_COLOR_MAP[getElement(strokes)] || '') : '';

  if (all.length === 0) {
    return '<span class="text-xs text-gray-400">此劃數無可用字</span>';
  }

  // 響應式 grid：auto-fill 依容器寬度自動決定欄數（手機約 8 欄、桌機約 16 欄），
  // 每格最小 38px 保持手指可點擊的大小，不會在窄螢幕擠成小格
  let inner = '';
  for (const ch of all) {
    const isCommon = common.includes(ch);
    inner += `<span class="h-9 rounded-lg flex items-center justify-center text-base cursor-pointer
      ${isCommon ? 'bg-emerald-100 font-bold border border-emerald-300 hover:bg-emerald-200' : 'bg-white border border-gray-200 hover:bg-blue-50'}
      ${elColor} transition-all" onclick="${onClickFn}('${ch}')" title="${ch} (${strokes || '?'}劃)">${ch}</span>`;
  }

  return `<div style="display:grid; grid-template-columns:repeat(auto-fill, minmax(38px, 1fr)); gap:3px; max-height:340px; overflow-y:auto; padding:4px;">${inner}</div>
    <div class="text-xs text-gray-400 mt-1">共 ${all.length} 字（綠底為常用字）</div>`;
}

